// フォロワー帯に応じたトーン調整
function getFollowerTone(followers: number): { greeting: string; closing: string } {
  if (followers >= 100000) {
    return {
      greeting: "突然のDM、大変失礼いたします。",
      closing: "お忙しいところ恐縮ですが、もしご興味をお持ちいただけましたら、ぜひ一度ご覧いただけると幸いです。",
    };
  }
  if (followers >= 50000) {
    return {
      greeting: "突然のDM失礼します。",
      closing: "もしご興味があれば、ぜひ一度ご覧ください！ご質問などもお気軽にどうぞ。",
    };
  }
  // 50000未満: 親しみやすいトーン
  return {
    greeting: "突然のDM失礼します！",
    closing: "よろしければぜひ一度覗いてみてください！ご質問やご要望もお気軽にどうぞ。一緒にコマパラを盛り上げていただけたら嬉しいです！",
  };
}

