// フォロワー帯に応じたトーン調整
function getFollowerTone(followers: number): { greeting: string; closing: string } {
  if (followers >= 100000) {
    return {
      greeting: "突然のDM、大変失礼いたします。",
      closing:
        "お忙しいところ恐縮です。今の段階でお声がけするのは面の皮が厚いと承知しておりますが、立ち上げ期だからこそ、○○さんのような方に最初に見ていただきたいと思いご連絡しました。ご興味をお持ちいただけましたら、まずは覗いていただくだけでも嬉しいです。",
    };
  }
  if (followers >= 50000) {
    return {
      greeting: "突然のDM失礼します。",
      closing:
        "まだ何もお約束できる段階ではないのですが、立ち上げ期だからこそ最初に声をかけたい方にご連絡しています。ご興味があれば、まずは覗いていただくだけでも嬉しいです。",
    };
  }
  return {
    greeting: "突然のDM失礼します！",
    closing:
      "まだ何もお約束できる段階ではないのですが、立ち上げ期だからこそ最初に声をかけたい方にご連絡しています。ご興味があれば、まずは覗いていただくだけでも嬉しいです。ご質問やご要望もお気軽にどうぞ。",
  };
}

